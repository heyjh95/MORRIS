import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";

const read = (path) => readFileSync(resolve(path), "utf8");
const pages = ["html/index.html", "html/en.html"];

test("IDs, ARIA references, fragment links and local assets resolve", () => {
  for (const path of pages) {
    const html = read(path);
    const ids = Array.from(html.matchAll(/\bid="([^"]+)"/g), m => m[1]);
    assert.equal(new Set(ids).size, ids.length, path + ": duplicate ID");
    for (const [, references] of html.matchAll(/\baria-(?:controls|labelledby)="([^"]+)"/g)) {
      for (const id of references.split(/\s+/)) assert.ok(ids.includes(id), path + ": missing " + id);
    }
    for (const [, id] of html.matchAll(/href="#([^"]+)"/g)) {
      assert.ok(ids.includes(id), path + ": missing fragment " + id);
    }
    for (const [, asset] of html.matchAll(/(?:src|href)="(\.\.?\/[^"#]+)"/g)) {
      assert.ok(existsSync(resolve(dirname(path), asset)), path + ": missing " + asset);
    }
    assert.doesNotMatch(html, /href=""|\{\{\{?\w+/);
    for (const [, content] of html.matchAll(/<button\b[^>]*>([\s\S]*?)<\/button>/g)) {
      assert.doesNotMatch(content, /<a\b/, path + ": nested link in button");
    }
  }
});

test("Slide buttons, panels and titles have matching counts for automatic ID pairing", () => {
  const groups = [
    ["main-visual-select", "main-visual-slide", "main-visual-card-title"],
    ["product-categories-button", "product-categories-panel", "product-categories-heading"],
    ["brands-tab", "brands-panel", "brands-brand-name"],
  ];
  const tagsWithClass = (html, cls) => Array.from(html.matchAll(/<[a-z][^>]*\bclass="([^"]+)"[^>]*>/g))
    .filter(match => match[1].split(/\s+/).includes(cls)).map(match => match[0]);
  for (const path of pages) {
    const html = read(path);
    for (const [buttonClass, panelClass, titleClass] of groups) {
      const buttons = tagsWithClass(html, buttonClass);
      const panels = tagsWithClass(html, panelClass);
      const titles = tagsWithClass(html, titleClass);
      assert.ok(panels.length > 0, path + ": no " + panelClass);
      assert.equal(buttons.length, panels.length, path + ": selector/panel count mismatch");
      assert.equal(titles.length, panels.length, path + ": title/panel count mismatch");
      for (const tag of [...buttons, ...panels, ...titles]) {
        assert.doesNotMatch(tag, /\s(?:id|aria-controls|aria-labelledby)="/, path + ": repeated IDs should be generated by JavaScript");
      }
      assert.equal(buttons.filter(tag => tag.includes('aria-pressed="true"')).length, 1, path);
    }
  }
});

test("Primary menu and drawer have matching addresses and labels", () => {
  for (const path of pages) {
    const html = read(path);
    const links = (cls) => Array.from(html.matchAll(new RegExp('<a class="' + cls + '" href="([^"]+)">([^<]+)</a>', "g")), m => [m[1], m[2]]);
    assert.ok(links("gnb-link").length > 0, path);
    assert.deepEqual(links("gnb-link"), links("header-drawer-link"), path);
  }
});

test("Both languages keep the same static IDs and local image order", () => {
  const ids = (path) => Array.from(read(path).matchAll(/\bid="([^"]+)"/g), m => m[1]);
  const images = (path) => Array.from(read(path).matchAll(/<img[^>]+src="([^"]+)"/g), m => m[1]);
  assert.deepEqual(ids(pages[0]), ids(pages[1]));
  assert.deepEqual(images(pages[0]), images(pages[1]));
});

test("Shared SVG arrows reference existing symbols", () => {
  for (const path of pages) {
    const references = Array.from(read(path).matchAll(/<use href="([^"]+)#([^"]+)"/g));
    assert.ok(references.length > 0, path);
    for (const [, asset, symbol] of references) {
      const source = readFileSync(resolve(dirname(path), asset), "utf8");
      assert.ok(source.includes('id="' + symbol + '"'), path + ": missing SVG symbol " + symbol);
    }
  }
});
